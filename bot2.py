async def cancel(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Отмена теста"""
    cancel_text = (
        f"❌ Тест отменён.\n"
        f"Хочешь начать заново?\n"
        f"👉 /start"
    )
    await update.message.reply_text(cancel_text)
    return ConversationHandler.END

