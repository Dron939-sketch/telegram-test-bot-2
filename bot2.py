# Функция для расчёта результата
def calculate_result(answers):
    """Вычисляет результат на основе ответов"""
    total = sum(answers)
    avg = total / len(answers)
    
    if avg <= 1:
        return "6"
    elif avg <= 2:
        return "7"
    elif avg <= 3:
        return "8"
    elif avg <= 4:
        return "9"
    elif avg <= 5:
        return "10"
    elif avg <= 6:
        return "Валет"
    elif avg <= 7:
        return "Дама"
    elif avg <= 8:
        return "Король"
    else:
        return "Туз"

