# Начало базового теста
async def start_base_test(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Начало базового теста"""
    query = update.callback_query
    await query.answer()
    
    context.user_data['current_question'] = 0
    context.user_data['base_answers'] = []
    context.user_data['stage'] = 'base'
    
    await send_question(query, context)
    return BASE_TEST

# Отправка вопроса
async def send_question(query, context):
    """Отправляет текущий вопрос"""
    stage = context.user_data['stage']
    question_num = context.user_data['current_question']
    
    if stage == 'base':
        # Базовый тест
        if question_num >= len(BASE_QUESTIONS):
            # Базовый тест завершён
            dominant_suit = calculate_base_result(context.user_data['base_answers'])
            context.user_data['dominant_suit'] = dominant_suit
            context.user_data['stage'] = 'deep'
            context.user_data['current_question'] = 0
            context.user_data['deep_answers'] = []
            
            text = f"""
✨ **БАЗОВЫЙ ТЕСТ ЗАВЕРШЁН!**

Твоя доминирующая программа:
**{dominant_suit}**

Теперь пройдём углублённый тест из 12 вопросов, чтобы точно определить твой уровень.

Готов продолжить? 👇
            """
            keyboard = [[InlineKeyboardButton("➡️ Продолжить", callback_data="continue_deep")]]
            reply_markup = InlineKeyboardMarkup(keyboard)
            
            await query.edit_message_text(text, reply_markup=reply_markup, parse_mode='Markdown')
            return
        
        question_data = BASE_QUESTIONS[question_num]
        question_text = f"**{question_data['question']}**\n\n📊 Вопрос {question_num + 1} из {len(BASE_QUESTIONS)}\n\nВыбери вариант:"
        
        # Создаём кнопки
        keyboard = []
        for key, option in question_data['options'].items():
            keyboard.append([InlineKeyboardButton(option, callback_data=f"answer_{key}")])
        
    else:
        # Углублённый тест
        dominant_suit = context.user_data['dominant_suit']
        deep_questions = DEEP_QUESTIONS[dominant_suit]
        
        if question_num >= len(deep_questions):
            # Тест завершён
            await show_result(query, context)
            return ConversationHandler.END
        
        question_data = deep_questions[question_num]
        question_text = f"**{question_data['question']}**\n\n📊 Углублённый тест: вопрос {question_num + 1} из {len(deep_questions)}\n\nВыбери вариант:"
        
        # Создаём кнопки
        keyboard = []
        for idx, option in enumerate(question_data['options']):
            keyboard.append([InlineKeyboardButton(option, callback_data=f"answer_{idx}")])
    
    reply_markup = InlineKeyboardMarkup(keyboard)
    
    await query.edit_message_text(
        text=question_text,
        reply_markup=reply_markup,
        parse_mode='Markdown'
    )

# Обработка ответа на базовый тест
async def handle_base_answer(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Обработка ответа на вопрос базового теста"""
    query = update.callback_query
    await query.answer()
    
    answer_value = query.data.replace("answer_", "")
    context.user_data['base_answers'].append(answer_value)
    context.user_data['current_question'] += 1
    
    await send_question(query, context)
    return BASE_TEST

# Продолжение на углублённый тест
async def continue_deep_test(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Переход к углублённому тесту"""
    query = update.callback_query
    await query.answer()
    
    await send_question(query, context)
    return DEEP_TEST

# Обработка ответа на углублённый тест
async def handle_deep_answer(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Обработка ответа на вопрос углублённого теста"""
    query = update.callback_query
    await query.answer()
    
    answer_value = int(query.data.replace("answer_", ""))
    context.user_data['deep_answers'].append(answer_value)
    context.user_data['current_question'] += 1
    
    await send_question(query, context)
    return DEEP_TEST

# Показ результата
async def show_result(query, context):
    """Показывает результат теста"""
    dominant_suit = context.user_data['dominant_suit']
    deep_answers = context.user_data['deep_answers']
    
    result_level = calculate_level(deep_answers)
    
    # Здесь подставляются полные описания из твоего текста
    result_text = f"""
✨ **ТВОЙ РЕЗУЛЬТАТ** ✨

{dominant_suit}-{result_level}

[Здесь будет полное описание из твоего текста]

━━━━━━━━━━━━━━━━━━━

📊 **Доминирующая программа:** {dominant_suit}
📈 **Уровень:** {result_level}

━━━━━━━━━━━━━━━━━━━

🔄 Хочешь пройти тест заново?
Нажми /start
    """
    
    keyboard = [[InlineKeyboardButton("🔄 Пройти ещё раз", callback_data="restart")]]
    reply_markup = InlineKeyboardMarkup(keyboard)
    
    await query.edit_message_text(
        text=result_text,
        reply_markup=reply_markup,
        parse_mode='Markdown'
    )

# Перезапуск
async def restart(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Перезапуск теста"""
    query = update.callback_query
    await query.answer()
    
    context.user_data.clear()
    
    text = "🎴 Готов пройти тест заново?"
    keyboard = [[InlineKeyboardButton("🚀 Начать тест", callback_data="start_test")]]
    reply_markup = InlineKeyboardMarkup(keyboard)
    
    await query.edit_message_text(text, reply_markup=reply_markup)

# Отмена
async def cancel(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Отмена диалога"""
    await update.message.reply_text("❌ Тест отменён. Нажми /start, чтобы начать заново.")
    return ConversationHandler.END

# Главная функция
def main():
    """Запуск бота"""
    logger.info("🤖 Запуск бота...")
    
    application = Application.builder().token(TOKEN).build()
    
    conv_handler = ConversationHandler(
        entry_points=[
            CommandHandler('start', start),
            CallbackQueryHandler(start_base_test, pattern="^start_test$")
        ],
        states={
            BASE_TEST: [CallbackQueryHandler(handle_base_answer, pattern="^answer_")],
            DEEP_TEST: [
                CallbackQueryHandler(continue_deep_test, pattern="^continue_deep$"),
                CallbackQueryHandler(handle_deep_answer, pattern="^answer_")
            ],
        },
        fallbacks=[
            CommandHandler('cancel', cancel),
            CallbackQueryHandler(restart, pattern="^restart$")
        ],
    )
    
    application.add_handler(conv_handler)
    
    logger.info("✅ Бот запущен и готов к работе!")
    application.run_polling(allowed_updates=Update.ALL_TYPES)

if __name__ == '__main__':
    main()
    
