# Функция расчёта результата базового теста
def calculate_base_result(answers):
    """Определяет доминирующую программу"""
    scores = {"A": 0, "B": 0, "C": 0, "D": 0}
    for answer in answers:
        scores[answer] += 1
    
    max_score = max(scores.values())
    dominant = [k for k, v in scores.items() if v == max_score][0]
    
    suit_map = {
        "A": "♠️ СИЛОВАЯ",
        "B": "♥️ ТЕЛЕСНАЯ",
        "C": "♣️ ПОЗНАВАТЕЛЬНАЯ",
        "D": "♦️ ЭМОЦИОНАЛЬНАЯ"
    }
    
    return suit_map[dominant]

# Функция расчёта уровня
def calculate_level(answers):
    """Определяет уровень (6-Туз)"""
    avg = sum(answers) / len(answers)
    
    if avg <= 0.5:
        return "6"
    elif avg <= 1.5:
        return "7"
    elif avg <= 2.5:
        return "8"
    elif avg <= 3.5:
        return "9"
    elif avg <= 4.5:
        return "10"
    elif avg <= 5.5:
        return "Валет"
    elif avg <= 6.5:
        return "Дама"
    elif avg <= 7.5:
        return "Король"
    else:
        return "Туз"

