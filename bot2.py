def calculate_stage_1_result(answers):
    """
    Подсчёт результата этапа 1
    Приоритет: ГЛУБИНА (D > C > B > A)
    """
    counts = {"A": 0, "B": 0, "C": 0, "D": 0}
    
    for answer in answers:
        counts[answer] += 1
    
    # Находим максимальное количество
    max_count = max(counts.values())
    
    # Находим все программы с максимальным счётом
    max_programs = [k for k, v in counts.items() if v == max_count]
    
    # Если несколько — выбираем по приоритету глубины (D > C > B > A)
    priority = ["D", "C", "B", "A"]
    for p in priority:
        if p in max_programs:
            return p
    
    return "A"  # Fallback

def calculate_stage_2_result(answers):
    """
    Подсчёт результата этапа 2
    Приоритет: ГЛУБИНА (Т > К > Д > В > 10 > 9 > 8 > 7 > 6)
    """
    counts = {}
    for answer in answers:
        counts[answer] = counts.get(answer, 0) + 1
    
    # Находим максимальное количество
    max_count = max(counts.values())
    
    # Находим все уровни с максимальным счётом
    max_levels = [k for k, v in counts.items() if v == max_count]
    
    # Приоритет: от Туза к 6
    priority = ["Т", "К", "Д", "В", "10", "9", "8", "7", "6"]
    for p in priority:
        if p in max_levels:
            return p
    
    return "6"  # Fallback

def map_program_code(letter):
    """Преобразовать букву в код программы"""
    mapping = {
        "A": "СБ",
        "B": "ТФ",
        "C": "УБ",
        "D": "ЧВ"
    }
    return mapping.get(letter, "СБ")

