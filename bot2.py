        f"**Ваш архетип:** {archetype}\n"
        f"**Программа:** {get_program_name(program)}\n"
        f"**Уровень:** {get_level_name(level)}\n\n"
        f"{description}\n\n"
        f"{recommendation}\n\n"
        f"📖 **Ваша терапевтическая сказка:**\n"
        f"[Читать сказку]({tale_link})\n\n"
        f"💡 Сказка поможет интегрировать конфликтующие части вашей личности."
