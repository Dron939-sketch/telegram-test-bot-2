# Выбор масти
async def choose_suit(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Обработка выбора масти"""
    query = update.callback_query
    await query.answer()
    
    suit = query.data.replace("suit_", "")
    context.user_data['suit'] = suit
    context.user_data['current_question'] = 0
    context.user_data['answers'] = []
    
    # Отправляем первый вопрос
    await send_question(query, context)
    return ANSWERING

# Отправка вопроса
async def send_question(query, context):
    """Отправляет текущий вопрос"""
    suit = context.user_data['suit']
    question_num = context.user_data['current_question']
    questions = QUESTIONS[suit]
    
    if question_num >= len(questions):
        # Тест завершён
        await show_result(query, context)
        return ConversationHandler.END
    
    question_data = questions[question_num]
    question_text = f"**{question_data['question']}**\n\nВыбери наиболее подходящий вариант:"
    
    # Создаём кнопки с вариантами ответов (БЕЗ цифр)
    keyboard = []
    for idx, option in enumerate(question_data['options']):
        keyboard.append([InlineKeyboardButton(option, callback_data=f"answer_{idx}")])
    
    reply_markup = InlineKeyboardMarkup(keyboard)
    
    await query.edit_message_text(
        text=question_text,
        reply_markup=reply_markup,
        parse_mode='Markdown'
    )

# Обработка ответа
async def handle_answer(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Обработка ответа на вопрос"""
    query = update.callback_query
    await query.answer()
    
    answer_value = int(query.data.replace("answer_", ""))
    context.user_data['answers'].append(answer_value)
    context.user_data['current_question'] += 1
    
    await send_question(query, context)
    return ANSWERING

# Показ результата
async def show_result(query, context):
    """Показывает результат теста"""
    suit = context.user_data['suit']
    answers = context.user_data['answers']
    
    result_level = calculate_result(answers)
    result_data = RESULTS[suit][result_level]
    
    result_text = f"""
✨ **ТВОЙ РЕЗУЛЬТАТ** ✨

{result_data['title']}

{result_data['description']}

━━━━━━━━━━━━━━━━━━━

📊 **Твои ответы:** {answers}
📈 **Средний балл:** {sum(answers)/len(answers):.1f}

━━━━━━━━━━━━━━━━━━━

🔄 Хочешь пройти тест по другой программе?
Нажми /start
    """
    
    keyboard = [[InlineKeyboardButton("🔄 Пройти ещё раз", callback_data="restart")]]
    reply_markup = InlineKeyboardMarkup(keyboard)
    
    await query.edit_message_text(
        text=result_text,
        reply_markup=reply_markup,
        parse_mode='Markdown'
    )
    
    # Сохраняем результат в Google Sheets
    await save_to_sheets(query.from_user, suit, result_level, answers)

# Сохранение в Google Sheets
async def save_to_sheets(user, suit, result, answers):
    """Сохраняет результат в Google Sheets"""
    try:
        import gspread
        from oauth2client.service_account import ServiceAccountCredentials
        
        scope = ['https://spreadsheets.google.com/feeds', 'https://www.googleapis.com/auth/drive']
        creds_dict = {
            "type": "service_account",
            "project_id": os.getenv("GOOGLE_PROJECT_ID"),
            "private_key_id": os.getenv("GOOGLE_PRIVATE_KEY_ID"),
            "private_key": os.getenv("GOOGLE_PRIVATE_KEY").replace('\\n', '\n'),
            "client_email": os.getenv("GOOGLE_CLIENT_EMAIL"),
            "client_id": os.getenv("GOOGLE_CLIENT_ID"),
            "auth_uri": "https://accounts.google.com/o/oauth2/auth",
            "token_uri": "https://oauth2.googleapis.com/token",
            "auth_provider_x509_cert_url": "https://www.googleapis.com/oauth2/v1/certs",
            "client_x509_cert_url": os.getenv("GOOGLE_CERT_URL")
        }
        
        creds = ServiceAccountCredentials.from_json_keyfile_dict(creds_dict, scope)
        client = gspread.authorize(creds)
        
        sheet = client.open_by_key(GOOGLE_DRIVE_FILE_ID).sheet1
        
        from datetime import datetime
        row = [
            datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            user.id,
            user.username or "Нет username",
            user.first_name or "",
            suit,
            result,
            str(answers)
        ]
        
        sheet.append_row(row)
        logger.info(f"✅ Результат сохранён в Google Sheets для пользователя {user.id}")
        
    except Exception as e:
        logger.error(f"❌ Ошибка сохранения в Google Sheets: {e}")

