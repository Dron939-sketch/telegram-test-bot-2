async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Команда /start"""
    keyboard = [
        [InlineKeyboardButton("🎯 Начать тест", callback_data="start_test")]
    ]
    reply_markup = InlineKeyboardMarkup(keyboard)
    
    await update.message.reply_text(
        "🎴 **ДИАГНОСТИКА БАЗОВЫХ ПРОГРАММ**\n\n"
        "Этот тест определит вашу доминирующую программу:\n\n"
        "♠️ **СИЛОВАЯ** — страх слабости/силы\n"
        "♥️ **ТЕЛЕСНАЯ** — страх болезни/здоровья\n"
        "♣️ **ПОЗНАВАТЕЛЬНАЯ** — страх глупости/ума\n"
        "♦️ **ЭМОЦИОНАЛЬНАЯ** — страх одиночества/близости\n\n"
        "📊 **Формат:**\n"
        "• 24 базовых вопроса (6 блоков × 4 вопроса)\n"
        "• Затем 12 углублённых вопросов по вашей программе\n"
        "• Итого: ~10 минут\n\n"
        "🎯 **Результат:**\n"
        "• Ваш архетип (из 36 карт)\n"
        "• Уровень развития (6-A)\n"
        "• Персональная сказка\n"
        "• Путь к следующему уровню\n\n"
        "Готовы начать?",
        reply_markup=reply_markup,
        parse_mode='Markdown'
    )

async def start_test(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Начало базового теста"""
    query = update.callback_query
    await query.answer()
    
    context.user_data['current_question'] = 0
    context.user_data['scores'] = {'A': 0, 'B': 0, 'C': 0, 'D': 0}
    context.user_data['deep_scores'] = []
    
    await send_question(update, context, 0)
    return BASE_TEST

async def send_question(update: Update, context: ContextTypes.DEFAULT_TYPE, question_num: int):
    """Отправка вопроса"""
    query = update.callback_query
    question = BASE_QUESTIONS[question_num]
    
    keyboard = []
    for key, text in question['options'].items():
        keyboard.append([InlineKeyboardButton(f"{key}. {text[:50]}...", callback_data=f"answer_{key}")])
    
    reply_markup = InlineKeyboardMarkup(keyboard)
    
    progress = f"📊 Вопрос {question_num + 1}/24"
    
    await query.edit_message_text(
        f"{progress}\n\n{question['question']}",
        reply_markup=reply_markup
    )

async def handle_answer(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Обработка ответа на базовый тест"""
    query = update.callback_query
    await query.answer()
    
    answer = query.data.split('_')[1]
    context.user_data['scores'][answer] += 1
    
    current = context.user_data['current_question']
    current += 1
    context.user_data['current_question'] = current
    
    if current < len(BASE_QUESTIONS):
        await send_question(update, context, current)
        return BASE_TEST
    else:
        # Базовый тест завершён
        scores = context.user_data['scores']
        max_score = max(scores.values())
        dominant = [k for k, v in scores.items() if v == max_score][0]
        
        program_names = {
            'A': '♠️ СИЛОВАЯ',
            'B': '♥️ ТЕЛЕСНАЯ',
            'C': '♣️ ПОЗНАВАТЕЛЬНАЯ',
            'D': '♦️ ЭМОЦИОНАЛЬНАЯ'
        }
        
        context.user_data['dominant_program'] = dominant
        
        await query.edit_message_text(
            f"✅ **Базовый тест завершён!**\n\n"
            f"📊 **Ваши результаты:**\n"
            f"♠️ Силовая: {scores['A']}\n"
            f"♥️ Телесная: {scores['B']}\n"
            f"♣️ Познавательная: {scores['C']}\n"
            f"♦️ Эмоциональная: {scores['D']}\n\n"
            f"🎯 **Доминирующая программа:**\n"
            f"{program_names[dominant]}\n\n"
            f"Сейчас начнётся углублённый тест (12 вопросов).",
            parse_mode='Markdown'
        )
        
        await asyncio.sleep(3)
        
        # Начало углублённого теста
        context.user_data['deep_question'] = 0
        await send_deep_question(update, context, 0)
        return DEEP_TEST

async def send_deep_question(update: Update, context: ContextTypes.DEFAULT_TYPE, question_num: int):
    """Отправка углублённого вопроса"""
    query = update.callback_query
    dominant = context.user_data['dominant_program']
    
    program_names = {
        'A': '♠️ СИЛОВАЯ',
        'B': '♥️ ТЕЛЕСНАЯ',
        'C': '♣️ ПОЗНАВАТЕЛЬНАЯ',
        'D': '♦️ ЭМОЦИОНАЛЬНАЯ'
    }
    
    questions = DEEP_QUESTIONS[program_names[dominant]]
    question = questions[question_num]
    
    keyboard = []
    for i, option in enumerate(question['options']):
        keyboard.append([InlineKeyboardButton(f"{i+1}. {option[:50]}...", callback_data=f"deep_{i}")])
    
    reply_markup = InlineKeyboardMarkup(keyboard)
    
    progress = f"📊 Углублённый вопрос {question_num + 1}/12"
    
    await query.edit_message_text(
        f"{progress}\n\n{question['question']}",
        reply_markup=reply_markup
    )

async def handle_deep_answer(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Обработка ответа на углублённый тест"""
    query = update.callback_query
    await query.answer()
    
    answer = int(query.data.split('_')[1])
    context.user_data['deep_scores'].append(answer)
    
    current = context.user_data['deep_question']
    current += 1
    context.user_data['deep_question'] = current
    
    if current < 12:
        await send_deep_question(update, context, current)
        return DEEP_TEST
    else:
        # Углублённый тест завершён
        await show_result(update, context)
        return ConversationHandler.END

async def show_result(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Показ результата"""
    query = update.callback_query
    
    dominant = context.user_data['dominant_program']
    deep_scores = context.user_data['deep_scores']
    
    # Вычисление среднего уровня
    avg_level = sum(deep_scores) / len(deep_scores)
    
    # Определение карты (6, 7, 8, 9, 10, J, Q, K, A)
    if avg_level < 1:
        level = '6'
    elif avg_level < 2:
        level = '7'
    elif avg_level < 3:
        level = '8'
    elif avg_level < 4:
        level = '9'
    elif avg_level < 5:
        level = '10'
    elif avg_level < 6:
        level = 'J'
    elif avg_level < 7:
        level = 'Q'
    elif avg_level < 8:
        level = 'K'
    else:
        level = 'A'
    
    program_symbols = {
        'A': '♠️',
        'B': '♥️',
        'C': '♣️',
        'D': '♦️'
    }
    
    card = f"{program_symbols[dominant]}-{level}"
    
    if card in ARCHETYPES:
        result = ARCHETYPES[card]
        
        message = (
            f"🎴 **ВАШ РЕЗУЛЬТАТ**\n\n"
            f"{result['title']}\n\n"
            f"{result['problem']}\n"
            f"{result['level']}\n\n"
            f"{result['description']}\n\n"
            f"📖 {result['fairy_tale']}\n"
            f"🔗 Читать сказку: {result['link']}\n\n"
            f"💡 **Что дальше?**\n"
            f"Изучите свою сказку — она покажет путь к следующему уровню.\n\n"
            f"Хотите пройти тест заново? /start"
        )
    else:
        message = "❌ Ошибка: карта не найдена. Попробуйте /start"
    
    await query.edit_message_text(message, parse_mode='Markdown')

async def cancel(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Отмена теста"""
    await update.message.reply_text("Тест отменён. Начать заново: /start")
    return ConversationHandler.END

