async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Команда /start"""
    keyboard = [[InlineKeyboardButton("🎯 Начать тест", callback_data="start_test")]]
    reply_markup = InlineKeyboardMarkup(keyboard)
    
    await update.message.reply_text(
        "🌟 **Добро пожаловать в Мастер-Тест!**\n\n"
        "Этот тест определит ваш архетип из 36 возможных.\n\n"
        "📊 **Тест состоит из 2 этапов:**\n"
        "1️⃣ 24 вопроса — определение программы\n"
        "2️⃣ 12 вопросов — определение уровня\n\n"
        "⏱ Время прохождения: 10-15 минут\n\n"
        "💡 **Важно:** Отвечайте честно, не думайте логически — чувствуйте телом.",
        reply_markup=reply_markup,
        parse_mode='Markdown'
    )
    
    return STAGE_1

async def start_test(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Начало теста"""
    query = update.callback_query
    await query.answer()
    
    # Инициализация
    context.user_data['stage'] = 1
    context.user_data['question_index'] = 0
    context.user_data['answers_stage_1'] = []
    context.user_data['answers_stage_2'] = []
    
    # Показываем первый вопрос
    await show_question(query, context)
    
    return STAGE_1

async def show_question(query, context):
    """Показать текущий вопрос"""
    stage = context.user_data['stage']
    index = context.user_data['question_index']
    
    if stage == 1:
        # Этап 1
        if index >= len(STAGE_1_QUESTIONS):
            # Этап 1 завершён
            await finish_stage_1(query, context)
            return STAGE_2
        
        question = STAGE_1_QUESTIONS[index]
        keyboard = []
        for key, value in question['options'].items():
            keyboard.append([InlineKeyboardButton(value, callback_data=f"ans_{key}")])
        
        reply_markup = InlineKeyboardMarkup(keyboard)
        
        await query.edit_message_text(
            question['text'],
            reply_markup=reply_markup,
            parse_mode='Markdown'
        )
    
    else:
        # Этап 2
        program = context.user_data['program']
        questions = STAGE_2_QUESTIONS[program]
        
        if index >= len(questions):
            # Этап 2 завершён
            await finish_stage_2(query, context)
            return ConversationHandler.END
        
        question = questions[index]
        keyboard = []
        for key, value in question['options'].items():
            keyboard.append([InlineKeyboardButton(f"{key}: {value[:30]}...", callback_data=f"ans_{key}")])
        
        reply_markup = InlineKeyboardMarkup(keyboard)
        
        await query.edit_message_text(
            question['text'],
            reply_markup=reply_markup,
            parse_mode='Markdown'
        )

async def handle_answer(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Обработка ответа"""
    query = update.callback_query
    await query.answer()
    
    answer = query.data.replace("ans_", "")
    stage = context.user_data['stage']
    
    if stage == 1:
        context.user_data['answers_stage_1'].append(answer)
    else:
        context.user_data['answers_stage_2'].append(answer)
    
    context.user_data['question_index'] += 1
    
    return await show_question(query, context)

async def finish_stage_1(query, context):
    """Завершение этапа 1"""
    answers = context.user_data['answers_stage_1']
    result = calculate_stage_1_result(answers)
    program = map_program_code(result)
    
    context.user_data['program'] = program
    context.user_data['stage'] = 2
    context.user_data['question_index'] = 0
    
    keyboard = [[InlineKeyboardButton("▶️ Продолжить", callback_data="continue_stage_2")]]
    reply_markup = InlineKeyboardMarkup(keyboard)
    
    await query.edit_message_text(
        f"✅ **Этап 1 завершён!**\n\n"
        f"Ваша программа: **{get_program_name(program)}**\n\n"
        f"Теперь определим ваш уровень в этой программе.\n"
        f"Осталось 12 вопросов.",
        reply_markup=reply_markup,
        parse_mode='Markdown'
    )

async def continue_stage_2(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Продолжение на этап 2"""
    query = update.callback_query
    await query.answer()
    
    return await show_question(query, context)

async def finish_stage_2(query, context):
    """Завершение этапа 2 и показ результата"""
    answers = context.user_data['answers_stage_2']
    level = calculate_stage_2_result(answers)
